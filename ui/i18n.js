  let lang = "en";

  const normalize = (l) => (String(l || "").toLowerCase().startsWith("tr") ? "tr" : "en");

  function t(key, params) {
    let s = dict[lang][key] ?? dict.en[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.split("{" + k + "}").join(String(v));
    return s;
  }

  /** Applies data-i18n* attributes to the static HTML. */
  function applyStatic(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
    root.querySelectorAll("[data-i18n-on]").forEach((el) => { el.dataset.on = t(el.dataset.i18nOn); });
    root.querySelectorAll("[data-i18n-off]").forEach((el) => { el.dataset.off = t(el.dataset.i18nOff); });
    document.documentElement.lang = lang;
    document.title = t("app.name");
  }

  function setLang(l) {
    lang = normalize(l);
    applyStatic();
  }

  window.I18N = {
    t,
    setLang,
    applyStatic,
    dict,
    get lang() { return lang; },
    get locale() { return lang === "tr" ? "tr-TR" : "en-US"; },
  };
